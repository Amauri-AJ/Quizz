function shuffle(obj1, obj2, obj3) {
    var index = obj1.length
    var rnd, tmp1, tmp2, tmp3

    while (index) {
        rnd = Math.floor(Math.random() * index)
        index -= 1
        tmp1 = obj1[index]
        tmp2 = obj2[index]
        tmp3 = obj3[index]
        obj1[index] = obj1[rnd]
        obj2[index] = obj2[rnd]
        obj3[index] = obj3[rnd]
        obj1[rnd] = tmp1
        obj2[rnd] = tmp2
        obj3[rnd] = tmp3
    }
}

